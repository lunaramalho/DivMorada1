import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { PGlite } from '@electric-sql/pglite';

test('payment requests enforce roles, conserve balances, preserve history and serialize conflicting decisions', async t => {
  const db = new PGlite();
  t.after(() => db.close());
  const creditor = '11111111-1111-4111-8111-111111111111';
  const debtor = '22222222-2222-4222-8222-222222222222';
  const other = '33333333-3333-4333-8333-333333333333';
  const outsider = '44444444-4444-4444-8444-444444444444';
  const house = 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
  const expense = 'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create schema auth; create schema storage;
    create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}');
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    create function auth.jwt() returns jsonb language sql stable as $$ select '{}'::jsonb $$;
    grant usage on schema public,auth to anon,authenticated,service_role;
    create table storage.buckets(id text primary key,name text,public boolean);
    create table storage.objects(id uuid,bucket_id text);`);
  await db.exec((await readFile('supabase-schema.sql', 'utf8')).replace('create extension if not exists "pgcrypto";', ''));
  await db.exec(`insert into auth.users(id,email) values('${creditor}','c@example.com'),('${debtor}','d@example.com'),('${other}','o@example.com'),('${outsider}','x@example.com');
    insert into residencias(id,nome,codigo) values('${house}','Casa','TEST');
    insert into residencia_usuarios("residenciaId","usuarioId",role) values('${house}','${creditor}','dono'),('${house}','${debtor}','membro'),('${house}','${other}','membro');
    insert into despesas(id,"residenciaId","criadoPorId",nome,"valorTotal",tipo) values('${expense}','${house}','${creditor}','Internet',100,'VARIAVEL');`);
  await db.exec(await readFile('supabase/migrations/202610240001_charge_email.sql', 'utf8'));
  await db.exec(await readFile('supabase/migrations/202611080001_payment_requests.sql', 'utf8'));
  const as = async user => { await db.exec(`reset role; select set_config('request.jwt.claim.sub','${user}',false); set role authenticated;`); };
  const query = async (sql, params = []) => (await db.query(sql, params)).rows;
  const newPayment = async (amount = 100) => {
    await db.exec('reset role');
    return (await query(`insert into pagamentos("residenciaId","despesaId","usuarioId",valor) values($1,$2,$3,$4) returning id`, [house, expense, debtor, amount]))[0].id;
  };
  const create = async (payment, type = 'PAGAMENTO', count = null, date = null, receipt = null) =>
    (await query('select to_jsonb(create_payment_request($1,$2,$3,$4,$5)) as r', [payment, type, count, date, receipt]))[0].r;
  const resolve = async (request, action) => (await query('select to_jsonb(resolve_payment_request($1,$2)) as r', [request, action]))[0].r;
  const direct = async payment => query('select confirm_direct_receipt($1)', [payment]);
  const get = async payment => (await query('select * from pagamentos where id=$1', [payment]))[0];
  const pendingSum = async () => Number((await query(`select coalesce(sum(valor),0) as value from pagamentos where status='PENDENTE'`))[0].value);

  const payment = await newPayment();
  await as(outsider);
  assert.equal((await query('select * from pagamentos')).length, 0);
  await assert.rejects(create(payment), /Acesso negado/);
  await as(creditor);
  await assert.rejects(create(payment), /Acesso negado/);
  await as(debtor);
  await assert.rejects(db.query(`update pagamentos set status='CONFIRMADO' where id=$1`, [payment]), /permission denied/);
  await assert.rejects(direct(payment), /Somente o credor/);
  await assert.rejects(create(payment, 'PARCELAMENTO', 1, '2096-01-31'), /invalido/);
  await assert.rejects(create(payment, 'PARCELAMENTO', 13, '2096-01-31'), /invalido/);
  await assert.rejects(create(payment, 'PARCELAMENTO', null, '2096-01-31'), /invalido/);
  await assert.rejects(create(payment, 'PARCELAMENTO', 3, '2000-01-01'), /partir de hoje/);
  await assert.rejects(create(payment, 'PAGAMENTO', null, null, 'https://untrusted.example/file.pdf'), /Comprovante invalido/);
  const informed = await create(payment);
  assert.equal(informed.comprovanteUrl, null);
  assert.equal((await get(payment)).status, 'PENDENTE');
  assert.equal(await pendingSum(), 100);
  const parallel = await Promise.allSettled([create(payment), create(payment, 'PARCELAMENTO', 3, '2096-01-31')]);
  assert.ok(parallel.every(result => result.status === 'rejected'));
  assert.equal((await query(`select * from payment_requests where status='PENDENTE'`)).length, 1);
  await assert.rejects(resolve(informed.id, 'APROVADA'), /Somente o credor/);
  await assert.rejects(db.exec(`update payment_requests set status='APROVADA'`), /permission denied/);
  await as(other);
  assert.equal((await query('select * from payment_requests')).length, 0);
  await assert.rejects(resolve(informed.id, 'APROVADA'), /Somente o credor/);
  await assert.rejects(direct(payment), /Somente o credor/);
  await as(creditor);
  await assert.rejects(resolve(informed.id, 'CANCELADA'), /Somente o devedor/);
  await resolve(informed.id, 'RECUSADA');
  assert.equal((await get(payment)).status, 'PENDENTE');
  assert.equal(await pendingSum(), 100);
  await as(debtor);
  const second = await create(payment);
  await resolve(second.id, 'CANCELADA');
  await resolve(second.id, 'CANCELADA');
  assert.equal(await pendingSum(), 100);
  const third = await create(payment);
  await as(creditor);
  await resolve(third.id, 'APROVADA');
  await resolve(third.id, 'APROVADA');
  assert.equal((await get(payment)).status, 'CONFIRMADO');
  assert.ok((await get(payment)).pagoEm);
  assert.equal(await pendingSum(), 0);
  await as(debtor);
  await assert.rejects(resolve(third.id, 'CANCELADA'), /ja encerrada/);
  await assert.rejects(create(payment), /indisponivel/);

  const splitPayment = await newPayment();
  await as(debtor);
  const split = await create(splitPayment, 'PARCELAMENTO', 3, '2096-01-31');
  assert.equal(await pendingSum(), 100);
  assert.equal((await query('select * from pagamentos where "pagamentoOriginalId"=$1', [splitPayment])).length, 0);
  await as(creditor);
  await resolve(split.id, 'APROVADA');
  await resolve(split.id, 'APROVADA');
  const children = await query('select *, vencimento::text as date from pagamentos where "pagamentoOriginalId"=$1 order by "numeroParcela"', [splitPayment]);
  assert.equal(children.length, 3);
  assert.equal((await get(splitPayment)).status, 'CANCELADO');
  assert.deepEqual(children.map(p => Number(p.valor)), [33.34, 33.33, 33.33]);
  assert.deepEqual(children.map(p => p.date), ['2096-01-31', '2096-02-29', '2096-03-31']);
  assert.equal(await pendingSum(), 100);
  await as(debtor);
  await assert.rejects(create(children[0].id, 'PARCELAMENTO', 2, '2096-01-31'), /nao pode ser parcelada/);
  await assert.rejects(db.query(`insert into pagamentos("residenciaId","despesaId","usuarioId",valor,"pagamentoOriginalId","numeroParcela","totalParcelas",vencimento) values($1,$2,$3,50,$4,4,4,'2096-01-31')`, [house, expense, debtor, splitPayment]), /permission denied/);
  const childRequest = await create(children[0].id);
  await as(creditor);
  await resolve(childRequest.id, 'APROVADA');
  assert.equal(await pendingSum(), 66.66);

  const directPayment = await newPayment(50);
  await as(debtor);
  const awaiting = await create(directPayment, 'PARCELAMENTO', 2, '2096-02-01');
  await as(creditor);
  await direct(directPayment);
  await direct(directPayment);
  assert.equal((await query('select status from payment_requests where id=$1', [awaiting.id]))[0].status, 'ENCERRADA');
  await assert.rejects(resolve(awaiting.id, 'APROVADA'), /ja encerrada/);
  assert.equal((await query('select * from pagamentos where "pagamentoOriginalId"=$1', [directPayment])).length, 0);
  assert.equal(await pendingSum(), 66.66);

  const withReceipt = await newPayment(20);
  await as(debtor);
  const receipt = `https://project.supabase.co/storage/v1/object/public/comprovantes/comprovantes/${debtor}/receipt.pdf`;
  const receivedRequest = await create(withReceipt, 'PAGAMENTO', null, null, receipt);
  await as(creditor);
  await direct(withReceipt);
  assert.equal((await get(withReceipt)).comprovanteUrl, receipt);
  await assert.rejects(resolve(receivedRequest.id, 'RECUSADA'), /ja encerrada/);
  assert.equal((await query(`select * from historicos where acao='Recebimento confirmado'`)).length, 4);

  const tiny = await newPayment(0.02);
  await as(debtor);
  await assert.rejects(create(tiny, 'PARCELAMENTO', 3, '2096-01-31'), /invalido/);
  const tinyRequest = await create(tiny, 'PARCELAMENTO', 2, '2096-01-31');
  await resolve(tinyRequest.id, 'CANCELADA');
  const newProposal = await create(tiny, 'PARCELAMENTO', 2, '2096-01-31');
  await as(creditor);
  await resolve(newProposal.id, 'RECUSADA');
  await as(debtor);
  assert.ok((await create(tiny, 'PARCELAMENTO', 2, '2096-01-31')).id);
  await db.exec('reset role; set role anon');
  await assert.rejects(create(tiny), /permission denied/);
});
